// Claude Code adapter.
// Generates: CLAUDE.md (imports AGENTS.md), .claude/settings.json (ECC + env), .mcp.json (crew + optional MCPs),
// .claude/skills/<name>/SKILL.md, .claude/agents/<role>.md.
// commit: true means the file is the same for everyone and is committed; false means it is machine-specific, kept in .gitignore.
import { statSync } from 'node:fs';
import { join, resolve } from 'node:path';

const isFile = (path) => { try { return statSync(path).isFile(); } catch { return false; } };

/**
 * Windows: launch without cmd /c (cmd parses &, %, parentheses and quotes in arguments its own way).
 * PATH order: native claude.exe, then the npm install (its binary or cli.js via node).
 */
export function windowsCommand(searchPath = '') {
  for (const entry of searchPath.split(';')) {
    const dir = entry.replace(/^"(.*)"$/, '$1');
    if (!dir) continue;
    const prefix = resolve(dir);
    if (isFile(join(prefix, 'claude.exe'))) return { cmd: join(prefix, 'claude.exe'), args: [] };
    if (!isFile(join(prefix, 'claude.cmd'))) continue;
    const pkg = join(prefix, 'node_modules', '@anthropic-ai', 'claude-code');
    if (isFile(join(pkg, 'bin', 'claude.exe'))) return { cmd: join(pkg, 'bin', 'claude.exe'), args: [] };
    if (isFile(join(pkg, 'cli.js'))) return { cmd: process.execPath, args: [join(pkg, 'cli.js')] };
  }
  return { cmd: 'claude.exe', args: [] }; // spawn will report that Claude is not installed; we do not use a shell
}

/**
 * What crew worker's agent may do without a human (claude -p cannot ask for permission: forbidden things are simply rejected).
 * File edits + build/tests + reading git; commit and PR only through crew (trailers, lease, checks).
 * Not allowed: git push/commit/reset directly, gh pr merge, arbitrary shell.
 */
export const HEADLESS_TOOLS = [
  'Read', 'Edit', 'Write', 'MultiEdit', 'Glob', 'Grep', 'TodoWrite', 'Task', 'Agent', 'mcp__crew',
  'Bash(crew:*)', 'Bash(crew.cmd:*)', 'Bash(npm:*)', 'Bash(npx:*)', 'Bash(node:*)', 'Bash(uv:*)',
  'Bash(git status:*)', 'Bash(git diff:*)', 'Bash(git log:*)', 'Bash(git show:*)',
  'Bash(git add:*)', 'Bash(git mv:*)', 'Bash(git rm:*)',
  'Bash(gh issue view:*)', 'Bash(gh pr view:*)', 'Bash(gh pr diff:*)',
];

const mcpEntry = (srv, platform) => {
  const winWrap = platform === 'win32' && ['npx', 'crew', 'npm'].includes(srv.command);
  const entry = winWrap ? { command: 'cmd', args: ['/c', srv.command, ...(srv.args ?? [])] } : { command: srv.command, args: srv.args ?? [] };
  const env = { ...(srv.env ?? {}) };
  for (const k of srv.env_from ?? []) env[k] = `\${${k}}`; // Claude Code expands ${VAR} from the environment
  if (Object.keys(env).length) entry.env = env;
  return entry;
};

export default {
  id: 'claude',
  binary: 'claude',

  generate({ config, roles, skills, frontmatter, platform }) {
    const files = [];

    files.push({
      path: 'CLAUDE.md',
      commit: true,
      content: '@AGENTS.md\n\n<!-- Generated by crew adapters build. All rules are in AGENTS.md; do not edit this file. -->\n',
    });

    const ecc = config.ecc ?? {};
    const settings = {
      env: { CREW_AGENT: 'claude' },
      permissions: { allow: ['Bash(crew:*)', 'Bash(crew.cmd:*)', 'Bash(gh issue view:*)', 'Bash(gh pr view:*)', 'mcp__crew'] },
    };
    if (ecc.enabled !== false) {
      settings.extraKnownMarketplaces = { ecc: { source: { source: 'git', url: ecc.marketplace ?? 'https://github.com/affaan-m/ECC.git' } } };
      settings.enabledPlugins = { 'ecc@ecc': true };
    }
    files.push({ path: '.claude/settings.json', commit: true, content: JSON.stringify(settings, null, 2) + '\n' });

    const servers = { crew: mcpEntry({ command: 'crew', args: ['mcp'], env: { CREW_AGENT: 'claude' } }, platform) };
    for (const [name, srv] of Object.entries(config.mcp ?? {})) if (srv.enabled) servers[name] = mcpEntry(srv, platform);
    files.push({ path: '.mcp.json', commit: false, content: JSON.stringify({ mcpServers: servers }, null, 2) + '\n' });

    for (const s of skills) files.push({ path: `.claude/skills/${s.name}/SKILL.md`, commit: false, content: s.content });

    for (const r of roles) {
      const { meta, body } = frontmatter(r.content);
      const model = config.tiers?.[meta.tier ?? 'mid']?.claude;
      const fm = [`name: ${r.name}`, `description: ${meta.description ?? r.name}`, model ? `model: ${model}` : null].filter(Boolean);
      files.push({ path: `.claude/agents/${r.name}.md`, commit: false, content: `---\n${fm.join('\n')}\n---\n${body}` });
    }
    return files;
  },

  /**
   * Headless run for crew worker. cwd = the task worktree (the worker starts the process in it).
   * #19 (M9): in -p mode nobody can be asked for permission, and .claude/settings.json allows only crew and gh view,
   * so file edits would be rejected. Hence: --permission-mode acceptEdits (edits in cwd without prompts)
   * and an explicit --allowedTools HEADLESS_TOOLS (each rule as a separate argument, as in the Claude Code docs).
   * Checked live on Claude Code 2.1.319: exit 0, a file edit without prompts, an allowed node command, CREW_AGENT in its shell.
   */
  headless({ prompt, model, platform = process.platform, searchPath = process.env.PATH ?? '' }) {
    const args = ['-p', prompt, '--output-format', 'json', '--permission-mode', 'acceptEdits'];
    if (model) args.push('--model', model);
    args.push('--allowedTools', ...HEADLESS_TOOLS);
    const launch = platform === 'win32' ? windowsCommand(searchPath) : { cmd: 'claude', args: [] };
    return {
      cmd: launch.cmd,
      args: [...launch.args, ...args],
      env: { CREW_AGENT: `claude/${model || 'default'}` },
    };
  },
};
