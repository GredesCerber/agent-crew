// Codex CLI adapter.
// Codex reads AGENTS.md from the repo root itself, so no instructions need to be generated.
// Generates: .codex/config.toml (MCP servers; Codex reads it only if the project is marked trusted),
// .agents/skills/<name>/SKILL.md (Codex project skills).
// Codex gets roles as role-<name> skills: no separate subagent format is needed.
import { statSync } from 'node:fs';
import { join, resolve } from 'node:path';

const isFile = (path) => { try { return statSync(path).isFile(); } catch { return false; } };

// Do not run npm's .cmd shim: cmd interprets &, %, quotes, etc. even with shell:false.
// Resolve supported native/npm installations in PATH order, keeping every argument literal.
function windowsCommand(searchPath) {
  for (const entry of searchPath.split(';')) {
    const dir = entry.replace(/^"(.*)"$/, '$1');
    if (!dir) continue;
    const prefix = resolve(dir);
    const binary = join(prefix, 'codex.exe');
    if (isFile(binary)) return { cmd: binary, args: [] };
    const script = join(prefix, 'node_modules', '@openai', 'codex', 'bin', 'codex.js');
    if (isFile(join(prefix, 'codex.cmd')) && isFile(script)) return { cmd: process.execPath, args: [script] };
  }
  // Let spawn report a missing native executable; never fall back to a shell script.
  return { cmd: 'codex.exe', args: [] };
}

const tomlStr = (s) => JSON.stringify(String(s)); // a JSON string is a valid TOML basic string
const tomlArr = (a) => `[${a.map(tomlStr).join(', ')}]`;

const serverBlock = (name, srv, platform) => {
  const winWrap = platform === 'win32' && ['npx', 'crew', 'npm'].includes(srv.command);
  const command = winWrap ? 'cmd' : srv.command;
  const args = winWrap ? ['/c', srv.command, ...(srv.args ?? [])] : srv.args ?? [];
  const lines = [`[mcp_servers.${name}]`, `command = ${tomlStr(command)}`, `args = ${tomlArr(args)}`];
  if (srv.env_from?.length) lines.push(`env_vars = ${tomlArr(srv.env_from)}`); // secrets only from the environment
  if (srv.approval) lines.push(`default_tools_approval_mode = ${tomlStr(srv.approval)}`);
  if (srv.env && Object.keys(srv.env).length) {
    lines.push(`env = { ${Object.entries(srv.env).map(([k, v]) => `${k} = ${tomlStr(v)}`).join(', ')} }`);
  }
  return lines.join('\n');
};

export default {
  id: 'codex',
  binary: 'codex',

  generate({ config, roles, skills, frontmatter, platform }) {
    const files = [];
    const blocks = [
      '# Generated by crew adapters build. Do not edit: change crew.config.json instead.',
      '# Codex reads this file only if the project is marked as trusted (run codex in the root and confirm).',
      '',
      '# Terminal commands Codex runs get CREW_AGENT too, so `crew ...` in its shell acts as this agent, not as "human".',
      '[shell_environment_policy]',
      'set = { CREW_AGENT = "codex" }',
      '',
      serverBlock('crew', {
        command: 'crew', args: ['mcp'], env: { CREW_AGENT: 'codex' },
        // Codex filters the MCP environment. Keep the worker's lease identity and gh auth,
        // but serialize only variable names, never credentials or a machine-specific id.
        env_from: ['CREW_AGENT_ID', 'GH_TOKEN', 'GITHUB_TOKEN', 'GH_HOST', 'GH_ENTERPRISE_TOKEN', 'GITHUB_ENTERPRISE_TOKEN'],
        // #12: codex exec (crew worker) runs with approval policy never; without this every crew_* call is rejected
        // ("MCP tool call requires approval, but approval policy is never"). We allow only the crew server:
        // over MCP it exposes only agent commands (agentCommands); dangerous init/labels/github setup are not included.
        // The key was verified against codex-cli 0.166 in a live run; other MCP servers keep requiring confirmation.
        approval: 'approve',
      }, platform),
    ];
    for (const [name, srv] of Object.entries(config.mcp ?? {})) if (srv.enabled) blocks.push('', serverBlock(name, srv, platform));
    files.push({ path: '.codex/config.toml', commit: false, content: blocks.join('\n') + '\n' });

    for (const s of skills) files.push({ path: `.agents/skills/${s.name}/SKILL.md`, commit: false, content: s.content });

    for (const r of roles) {
      const { meta, body } = frontmatter(r.content);
      const content = `---\nname: role-${r.name}\ndescription: ${meta.description ?? r.name}\n---\n${body}`;
      files.push({ path: `.agents/skills/role-${r.name}/SKILL.md`, commit: false, content });
    }
    return files;
  },

  /**
   * Headless run for crew worker. Flags verified against `codex exec --help` (codex-cli 0.166):
   *   -C <dir>              agent working root (the task worktree)
   *   -s workspace-write    file edits and commands inside the worktree, no confirmations
   *   -c sandbox_workspace_write.network_access=true  - needed for gh/git push in crew pr open
   *   --add-dir <dir>       extra writable folders: the repo's shared .git (a commit from the worktree writes there)
   *   --json                JSONL events on stdout (go to the worker log)
   *   -                     the prompt is read from stdin; on Windows it runs without cmd /c
   */
  headless({ prompt, model, cwd, writableDirs = [], platform = process.platform, searchPath = process.env.PATH ?? '' }) {
    const args = ['exec', '--json', '-s', 'workspace-write', '-c', 'sandbox_workspace_write.network_access=true'];
    if (cwd) args.push('-C', cwd);
    for (const d of writableDirs) args.push('--add-dir', d);
    if (model) args.push('--model', model);
    args.push('-');
    const launch = platform === 'win32' ? windowsCommand(searchPath) : { cmd: 'codex', args: [] };
    return {
      cmd: launch.cmd,
      args: [...launch.args, ...args],
      input: prompt,
      env: { CREW_AGENT: `codex/${model || 'default'}` },
    };
  },
};
